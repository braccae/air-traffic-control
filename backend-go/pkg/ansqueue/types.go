// Package ansqueue ports the Ansible mutation queue (on-the-fly playbook
// staging, one-by-one execution with checkpoint halting, and the five
// /api/queue* routes) from src/utils/ansibleQueueCompiler.ts,
// src/utils/ansibleQueueRunner.ts and server.ts to the Go daemon.
//
// Every type mirrors the TypeScript wire contract field-for-field so a
// task_json row written by either implementation is readable by the other.
// The engine never fabricates a result: an unreachable host, a failed module,
// or unparseable ansible output produces a failure with the real error text.
//
// Module policy (AGENTS.md §5): task builders stay native-first
// (ansible.builtin.*, ansible.posix.*, containers.podman.*). ansible.builtin.shell
// and ansible.builtin.command are a documented last resort only and are never
// generated by a builder in this package.
package ansqueue

import "encoding/json"

// Status is a queued task's lifecycle state.
type Status string

// The five status values of the TS `QueuedAnsibleTask['status']` union.
const (
	StatusStaged    Status = "staged"
	StatusRunning   Status = "running"
	StatusCompleted Status = "completed"
	StatusFailed    Status = "failed"
	StatusCancelled Status = "cancelled"
)

// Connection is the optional per-task connection block. Every field is
// optional in the TS `QueuedAnsibleTask.connection` shape.
type Connection struct {
	Plugin       string   `json:"plugin,omitempty"`
	Host         string   `json:"host,omitempty"`
	Port         int      `json:"port,omitempty"`
	User         string   `json:"user,omitempty"`
	BecomeMethod string   `json:"becomeMethod,omitempty"`
	ExtraArgs    []string `json:"extraArgs,omitempty"`
	ProxyCommand string   `json:"proxyCommand,omitempty"`
}

// Step is one declarative Ansible task inside a queued task.
type Step struct {
	Name       string         `json:"name"`
	Module     string         `json:"module"`
	Parameters map[string]any `json:"parameters"`
}

// Task mirrors the TS QueuedAnsibleTask interface. The JSON tags are the exact
// camelCase keys of src/types/index.ts so `task_json` stays cross-readable.
type Task struct {
	ID              string            `json:"id"`
	Title           string            `json:"title"`
	TargetNodeID    string            `json:"targetNodeId"`
	TargetNodeName  string            `json:"targetNodeName"`
	TargetHostRoute string            `json:"targetHostRoute"`
	TargetSSHUser   string            `json:"targetSshUser"`
	TargetSSHPort   int               `json:"targetSshPort"`
	Connection      *Connection       `json:"connection,omitempty"`
	Category        string            `json:"category"`
	PrimaryModule   string            `json:"primaryModule"`
	Steps           []Step            `json:"steps"`
	SecretsMasked   map[string]string `json:"secretsMasked,omitempty"`
	// Become is a pointer so "absent" (an API payload that never set it) is
	// distinguishable from an explicit false: enqueueTask defaults it to true,
	// exactly like the TS `task.become !== undefined ? Boolean(task.become) : true`.
	Become       *bool  `json:"become"`
	BecomeMethod string `json:"becomeMethod,omitempty"`
	Status       Status `json:"status"`
	CreatedAt    int64  `json:"createdAt"`
	Error        string `json:"error,omitempty"`
	ExecutedAt   int64  `json:"executedAt,omitempty"`

	// Extra carries JSON keys this struct does not model (for example the
	// `playbookRun` block the TS coordinator stores in task_json). The table is
	// shared with server.ts during the migration, so a row written by either
	// side must come back out verbatim: dropping unknown keys would silently
	// destroy data the TS side still reads.
	Extra map[string]json.RawMessage `json:"-"`
}

// taskKnownKeys is every key Task models itself. Anything else unmarshalled
// from task_json is preserved in Task.Extra.
var taskKnownKeys = []string{
	"id", "title", "targetNodeId", "targetNodeName", "targetHostRoute",
	"targetSshUser", "targetSshPort", "connection", "category", "primaryModule",
	"steps", "secretsMasked", "become", "becomeMethod", "status", "createdAt",
	"error", "executedAt",
}

// UnmarshalJSON decodes the modelled fields and keeps every unmodelled key in
// Extra so a round-trip through Go never loses TS-side data.
func (t *Task) UnmarshalJSON(data []byte) error {
	type taskAlias Task
	var alias taskAlias
	if err := json.Unmarshal(data, &alias); err != nil {
		return err
	}
	*t = Task(alias)

	var raw map[string]json.RawMessage
	if err := json.Unmarshal(data, &raw); err != nil {
		return err
	}
	for _, k := range taskKnownKeys {
		delete(raw, k)
	}
	if len(raw) == 0 {
		t.Extra = nil
	} else {
		t.Extra = raw
	}
	return nil
}

// MarshalJSON emits the modelled fields followed by Extra, so task_json and the
// GET /api/queue payload match what the TS coordinator would have written.
func (t Task) MarshalJSON() ([]byte, error) {
	type taskAlias Task
	body, err := marshalNoEscape(taskAlias(t))
	if err != nil {
		return nil, err
	}
	if len(t.Extra) == 0 {
		return body, nil
	}

	merged := make(map[string]json.RawMessage, len(t.Extra)+len(taskKnownKeys))
	if err := json.Unmarshal(body, &merged); err != nil {
		return nil, err
	}
	for k, v := range t.Extra {
		if _, taken := merged[k]; !taken {
			merged[k] = v
		}
	}
	return marshalNoEscape(merged)
}

// BecomeEnabled reports whether the task asks for privilege escalation.
// A nil Become is treated as false at playbook-compile time (the playbook
// generator mirrors the TS truthiness check); enqueueTask normalises it to true.
func (t Task) BecomeEnabled() bool { return t.Become != nil && *t.Become }

// BoolPtr returns a pointer to b, for Task.Become.
func BoolPtr(b bool) *bool { return &b }

// ExecutionResult mirrors the TS QueueExecutionResult: it is the `result`
// object inside the /api/queue/execute envelope.
type ExecutionResult struct {
	Success    bool   `json:"success"`
	TaskID     string `json:"taskId"`
	Changed    bool   `json:"changed"`
	Failed     bool   `json:"failed"`
	JSONOutput any    `json:"jsonOutput"`
	Error      string `json:"error,omitempty"`
	DurationMs int64  `json:"durationMs,omitempty"`
}

// ExecuteOutcome is the outcome of one ExecuteNextTask call. It marshals to the
// same keys as the TS executeNextQueueTask return value.
type ExecuteOutcome struct {
	Result         *ExecutionResult `json:"result"`
	RemainingCount int              `json:"remainingCount"`
	HaltedOnError  bool             `json:"haltedOnError"`
}

// Outcome is an alias for ExecuteOutcome (spec naming).
type Outcome = ExecuteOutcome

// QueueState is the queue snapshot the GET /api/queue route and the websocket
// events carry.
type QueueState struct {
	Tasks     []Task `json:"tasks"`
	IsRunning bool   `json:"isRunning"`
}

// MarshalTaskJSON renders a task exactly as it is persisted in task_json.
// encoding/json escapes HTML by default; the TS side does not, so the encoder
// is configured to match (titles legitimately contain < and &).
func MarshalTaskJSON(t Task) ([]byte, error) { return marshalNoEscape(t) }
